                    mime_type = attachment.get('mimeType') or attachment.get('type') or 'application/octet-stream'
                    size_bytes = attachment.get('size') or 0
                    size_kb = int(size_bytes / 1024) if size_bytes else 0
                    summary_lines.append(f"{idx}. {name} ({mime_type}, ~{size_kb} KB)")
