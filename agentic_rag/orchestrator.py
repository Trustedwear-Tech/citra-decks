    async def process_query_for_streaming(
        self,
        query: str,
        user_id: str,
        user_email: Optional[str] = None,
        use_personal_data: bool = True,
        use_enterprise_data: bool = False,
        org_id: Optional[str] = None,
        dept_id: Optional[str] = None,
        roles: Optional[List[str]] = None,
        conversation_history: Optional[List[Dict]] = None,
        multimodal_attachments: Optional[List[Dict[str, Any]]] = None,
        additional_sources: Optional[Dict[str, Any]] = None,
        persona_data: Optional[Dict] = None,
        enable_internet_search: bool = False,
        stage_emit: Optional[Any] = None,
    ) -> Dict[str, Any]:
        """
        Process query through retrieval pipeline WITHOUT generating the final response.
        
        This method is designed for streaming: it retrieves and merges contexts,
        then returns them so the caller can stream the LLM response separately.
        
        Returns:
            Dict with context_chunks, persona_system_prompt, conversation_messages, etc.
        """
        start_time = time.time()
        
        try:
            logger.info(f"🚀 [STREAMING_PREP] Preparing context for streaming query: '{query[:100]}...'")
            
            # Use conversation history directly — last-5 selection happens downstream
            processed_conversation_history = conversation_history or []
            
            # Extract additional source flags
            additional_sources = additional_sources or {}
            selected_folder_ids = additional_sources.get('selected_folder_ids', [])
            folder_search_enabled = additional_sources.get('folder_search_enabled', False)
            
            attachments = multimodal_attachments or []

            # Best-effort STAGE emitter — wraps the optional callback so failures
            # in the timeline never break the retrieval pipeline.
            def _emit(stage: str, label: str, detail: Optional[str] = None) -> None:
                if stage_emit is None:
                    return
                try:
                    stage_emit(stage, label, detail)
                except Exception as _e:  # noqa: BLE001
                    logger.debug(f"[STREAMING_PREP] stage_emit failed for {stage}: {_e}")

            # Build a modified graph that stops BEFORE generate_response
            # OR manually run the retrieval steps
            
            # Initialize state for retrieval-only processing
            initial_state = QueryState(
                query=query,
                user_id=user_id,
                user_email=user_email,
                use_personal_data=use_personal_data,
                use_enterprise_data=use_enterprise_data,
                org_id=org_id,
                dept_id=dept_id,
                roles=roles or ["user"],
                conversation_history=processed_conversation_history,
                multimodal_attachments=attachments,
                persona_data=persona_data,
                enable_internet_search=enable_internet_search,
                personal_contexts=[],
                enterprise_contexts=[],
                kg_contexts=[],
                strategies_executed=[],
                error_messages=[],
                metadata={
                    'additional_sources': additional_sources,
                    'selected_folder_ids': selected_folder_ids,
                    'folder_search_enabled': folder_search_enabled
                }
            )
            
            # Step 1: Analyze query — cheap (profession/persona; the sub-query
            # planner LLM was removed). NO retrieval, NO merge, NO relevance
            # scorer here: main chat is PURE AGENTIC. The chat LLM fetches vault
            # docs (list_vault_files → personal_data_tool / execute_code) and
            # enterprise data (dept_* tools) on demand. We pre-fetch NOTHING —
            # only a cheap POINTER (file count) so the agent knows the vault is
            # worth a look. This is the first-token-latency win: the stream
            # starts right after persona, with no pre-stream retrieval round-trips.
            _emit("analyzing_query", "Reading your request")
            state = await self.analyze_query(initial_state)

            # Cheap vault pointer — count only (indexed count_documents, no
            # listing, no LLM). Handed to the agent as "you have N files".
            vault_summary = None
            if use_personal_data and state.get('user_id'):
                try:
                    from services.vault_inventory import count_vault_files
                    vault_summary = await count_vault_files(
                        state['user_id'], selected_folder_ids or [],
                    )
                except Exception as _vc_exc:  # noqa: BLE001
                    logger.warning(f"⚠️ [STREAMING_PREP] vault count failed (non-fatal): {_vc_exc}")
            _emit("context_ready", "Ready")
            
            # Get persona system prompt
            persona_system_prompt = None
            profession = None
            if persona_data:
                try:
                    import sys
                    import os
                    parent_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
                    if parent_dir not in sys.path:
                        sys.path.insert(0, parent_dir)
                    from persona import generate_persona_system_prompt
                    persona_system_prompt = generate_persona_system_prompt(persona_data)
                    persona_info = persona_data.get('persona', {})
                    profession = persona_info.get('profession', persona_data.get('profession'))
                    logger.info(f"🎯 [STREAMING_PREP] Generated persona prompt for: {profession}")
                except Exception as e:
                    logger.warning(f"🎯 [STREAMING_PREP] Error generating persona prompt: {e}")
            
            # Prepare conversation messages - keep last 5: user queries full, bot replies truncated to 400 words
            conversation_messages = []
            if processed_conversation_history:
                for msg in processed_conversation_history[-5:]:
                    if isinstance(msg, dict):
                        role = msg.get('role', 'user')
                        content = msg.get('content', msg.get('message', msg.get('user_query', ''))).strip()
                        if content:
                            # Truncate bot replies to 400 words, keep user queries full
                            if role != 'user':
                                words = content.split()
                                if len(words) > 400:
                                    content = ' '.join(words[:400]) + "..."
                            conversation_messages.append({
                                'role': role,
                                'content': content
                            })
            
            # PURE AGENTIC: no prefetched context. The chat LLM retrieves on
            # demand via tools, so we never push chunks into the prompt.
            context_chunks = []

            # Grounding signal is POINTER-based, not prefetch-based. The user
            # "has context" if their vault has files OR enterprise is on — the
            # agent will fetch it via tools. We do NOT inject the no-context
            # wrapper merely because nothing was prefetched (there is no
            # prefetch), and we do NOT force internet off an empty-prefetch
            # signal — the agent decides when to call internet_search.
            grounding_payload: Dict[str, Any] = {}
            resolved_temperature: Optional[float] = None
            try:
                _vault_total = int((vault_summary or {}).get('total', 0) or 0)
                _has_sources = _vault_total > 0 or bool(use_enterprise_data)
                effective_internet = bool(enable_internet_search)
                grounding_payload = {
                    "has_context": _has_sources,
                    "agentic": True,
                    "vault_files": _vault_total,
                    "internet_used": effective_internet,
                    "user_enable_internet": enable_internet_search,
                }
                # Only when the user has NO sources at all (empty vault AND no
                # enterprise) do we add the no-context guidance.
                if not _has_sources:
                    try:
                        from prompts.grounding import no_context_wrapper
                        persona_system_prompt = (
                            (persona_system_prompt or "")
                            + "\n\n---\n\n"
                            + no_context_wrapper(internet_available=effective_internet)
                        )
                        logger.info("🛡️ [STREAMING_PREP] No vault/enterprise sources — no-context wrapper added")
                    except Exception as _w_err:  # noqa: BLE001
                        logger.warning(f"⚠️ no-context wrapper injection failed: {_w_err}")
                enable_internet_search = effective_internet
            except Exception as _g_err:  # noqa: BLE001
                logger.warning(f"⚠️ [STREAMING_PREP] Grounding (agentic) error: {_g_err}")

            # 🌡️ Profession-aware temperature
            try:
                from llm.llm_defaults import temperature_for
                resolved_temperature = temperature_for()
            except Exception:
                resolved_temperature = None

            # 📊 Best-effort grounding metrics for streaming path
            try:
                from metrics import record_grounding
                record_grounding(
                    feature='main_chat_stream',
                    chunks_used=len(context_chunks) if context_chunks else 0,
                    context_empty=bool(grounding_payload and not grounding_payload.get('has_context', True)),
                    temperature=resolved_temperature,
                    internet_used=bool(enable_internet_search),
                    internet_reason=str(grounding_payload.get('internet_decision_reason', '')),
                )
            except Exception as _m_err:
                logger.debug(f"record_grounding (stream) skipped: {_m_err}")

            processing_time = time.time() - start_time
            logger.info(f"✅ [STREAMING_PREP] Context ready in {processing_time:.2f}s - {len(context_chunks)} chunks")

            return {
                'context_chunks': context_chunks,
                'merged_context': state.get('merged_context', ''),
                'persona_system_prompt': persona_system_prompt,
                'profession': profession,
                'conversation_messages': conversation_messages,
                'strategies_used': state.get('strategies_executed', []),
                'query_intent': state.get('query_intent'),
                'processing_time': processing_time,
                'metadata': state.get('metadata', {}),
                'grounding': grounding_payload,
                'enable_internet_search': enable_internet_search,
                'temperature': resolved_temperature,
                # Cheap agentic pointer — {structured, unstructured, total} file
                # counts so the chat prompt can tell the agent the vault exists.
                'vault_summary': vault_summary,
            }
            
        except Exception as e:
            logger.error(f"❌ [STREAMING_PREP] Error preparing context: {e}")
            return {
                'context_chunks': [],
                'merged_context': '',
                'persona_system_prompt': None,
                'profession': None,
                'conversation_messages': [],
                'strategies_used': [],
                'error': str(e),
                'processing_time': time.time() - start_time
            }

    async def process_query(
        self,
        query: str,
        user_id: str,
        user_email: Optional[str] = None,
        entity_id: Optional[str] = None,
        entity_name: Optional[str] = None,
        entity_type: Optional[str] = None,
        use_personal_data: bool = True,
        use_enterprise_data: bool = False,
        enterprise_user_info: Optional[Dict[str, Any]] = None,
        org_id: Optional[str] = None,
        dept_id: Optional[str] = None,
        roles: Optional[List[str]] = None,
        conversation_history: Optional[List[Dict]] = None,
        multimodal_attachments: Optional[List[Dict[str, Any]]] = None,
        additional_sources: Optional[Dict[str, Any]] = None,
        model_only_mode: bool = False,
        persona_data: Optional[Dict] = None,
        enable_internet_search: bool = True,
        legal_collection_ids: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """
        Main entry point for processing queries through the agentic RAG system

        ⚠️ LEGACY (non-streaming). Main chat has SHIFTED TO STREAMING:
        process_query_for_streaming() is the live path (called by /query/stream).
        This method runs the full LangGraph including the generate_response node
        and is only reached by the legacy non-streaming /query route. Keep it
        behaviour-aligned with the streaming path until /query is retired; add new
        chat behaviour to the streaming path, not here.

        Args:
            query: User's query text
            user_id: User's device ID
            entity_id: Optional entity ID for filtering
            entity_name: Optional entity name for context
            entity_type: Optional entity type for routing decisions
            use_personal_data: Whether to include personal data
            use_enterprise_data: Whether to include enterprise data
            enterprise_user_info: User identity from middleware (required for enterprise: {"user_id": str, "email": str})
            conversation_history: Previous conversation context
            multimodal_attachments: Raw attachments (images/audio/video) to include in LLM call
            additional_sources: Additional source flags (deep_research, selected_folder_ids for project management, etc.)
            model_only_mode: If True, skip all data retrieval and use direct LLM call
            persona_data: User persona data from the query API
            
        Returns:
            Dict with response and metadata
        """
        start_time = time.time()
        
        try:
            logger.info(f"🚀 Starting agentic RAG processing for query: '{query[:100]}...'")
            
            # 📝 CONVERSATION: Pass through directly — last-5 selection happens downstream
            processed_conversation_history = conversation_history or []

            # Extract additional source flags
            additional_sources = additional_sources or {}
            deep_research = additional_sources.get('deep_research', False)
            query_type = additional_sources.get('query_type', None)
            
            # Extract folder filtering data
            selected_folder_ids = additional_sources.get('selected_folder_ids', [])
            folder_search_enabled = additional_sources.get('folder_search_enabled', False)
            
            # Extract legal collection IDs from additional sources
            legal_collections_from_additional = additional_sources.get('legal_collection_ids', [])
            
            # Log all source configurations
            logger.info(f"📊 Source Configuration:")
            logger.info(f"   🏠 Personal Data: {use_personal_data}")
            logger.info(f"   🏢 Enterprise Data: {use_enterprise_data}")
            logger.info(f"   🔬 Deep Research: {deep_research}")
            logger.info(f"   📋 Query Type: {query_type}")
            logger.info(f"   📁 Folder Filtering: {folder_search_enabled}")
            logger.info(f"   📂 Selected Folders: {selected_folder_ids}")
            logger.info(f"   🤖 Model Only Mode: {model_only_mode}")
            logger.info(f"   ⚖️ Legal Collection IDs: {legal_collection_ids or legal_collections_from_additional}")

            attachments = multimodal_attachments or []
            if attachments:
                attachment_summaries = []
                for att in attachments:
                    name = att.get('name') or att.get('id') or 'unnamed-attachment'
                    mime_type = att.get('mimeType') or att.get('type') or 'application/octet-stream'
                    size_bytes = att.get('size') or 0
                    size_kb = int(size_bytes / 1024) if size_bytes else 0
                    attachment_summaries.append(f"{name} [{mime_type}, ~{size_kb} KB]")
                logger.info(f"📎 Multimodal attachments provided: {attachment_summaries}")
            else:
                logger.info("📎 No multimodal attachments provided")
            
            # � SECURITY: Log enterprise authentication status
            logger.info(f"🏢 [ORCHESTRATOR] Enterprise user_info provided: {bool(enterprise_user_info)}")
            if enterprise_user_info:
                logger.info(f"🏢 [ORCHESTRATOR] Enterprise user_id: {enterprise_user_info.get('user_id')}")
            else:
                logger.info("🏢 [ORCHESTRATOR] No enterprise authentication provided")
            
            # 🚀 FAST PATH: Handle model-only mode immediately without LangGraph processing
            if model_only_mode:
                logger.info("⚡ Model-only mode detected - executing fast path")
                logger.info(f"🌐 [ORCHESTRATOR_FAST_PATH] Internet search: {'ENABLED' if enable_internet_search else 'DISABLED'}")
                
                try:
                    # Import here to avoid circular imports
                    import sys
                    import os
                    # Add parent directory to path so we can import query module
                    parent_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
                    if parent_dir not in sys.path:
                        sys.path.insert(0, parent_dir)
                    from query import reply
                    
                    # 🎭 PERSONA INTEGRATION: Generate persona-aware system prompt for model-only
                    persona_system_prompt = None
                    profession = None  # Extract profession for collections access control
                    try:
                        if persona_data:
                            from persona import generate_persona_system_prompt
                            persona_system_prompt = generate_persona_system_prompt(persona_data)
                            
                            # Log the actual profession from persona data and extract for collections check
                            persona_info = persona_data.get('persona', {})
                            profession = persona_info.get('profession', persona_data.get('profession'))  # Handle nested and flat structures
                            logger.info(f"🎯 [MODEL-ONLY FAST PATH] Generated persona-aware system prompt for profession: {profession}")
                        else:
                            logger.info("🎯 [MODEL-ONLY FAST PATH] No persona data provided - using default prompt")
                    except ImportError:
                        logger.warning("🎯 [MODEL-ONLY FAST PATH] Persona module not available")
                    except Exception as e:
                        logger.warning(f"🎯 [MODEL-ONLY FAST PATH] Error generating persona prompt: {e}")

                    # Build structured conversation messages (last 5, user full, bot 400w)
                    conversation_messages = []
                    if processed_conversation_history:
                        for msg in processed_conversation_history[-5:]:
                            if isinstance(msg, dict):
                                role = msg.get('role', 'user')
                                content = msg.get('content', msg.get('message', msg.get('user_query', ''))).strip()
                                if content:
                                    if role != 'user':
                                        words = content.split()
                                        if len(words) > 400:
                                            content = ' '.join(words[:400]) + "..."
                                    conversation_messages.append({'role': role, 'content': content})

                    # Choose model: LLM for all queries (text and image)
                    
                    has_image_attachments = any(
                        (att.get('mimeType') or att.get('type') or '').lower().startswith('image/')
                        for att in (attachments or [])
                    )
                    
                    if has_image_attachments:
                        model_to_use = get_default_model()
                        logger.info(f"🖼️ [DEBUG_FAST_PATH] Image attachment detected - using {model_to_use}")
                    else:
                        model_to_use = get_default_model()
                        logger.info(f"📝 [DEBUG_FAST_PATH] Text-only query - using {model_to_use}")
                    
                    # DEBUG: Log before calling reply()
                    logger.info(f"🔍 [DEBUG_FAST_PATH] About to call reply() with:")
                    logger.info(f"  - model: {model_to_use}")
                    logger.info(f"  - query len: {len(query)} chars")
                    logger.info(f"  - conversation_history: {len(conversation_messages)} messages")
                    logger.info(f"  - enable_internet_search: {enable_internet_search}")
                    logger.info(f"  - attachments: {len(attachments) if attachments else 0}")
                    
                    direct_response = reply(
                        query,
                        model_to_use,
                        system=persona_system_prompt,
                        attachments=attachments,
                        enable_internet_search=enable_internet_search,
                        user_id=user_id,
                        user_email=user_email,
                        profession=profession,
                        conversation_history=conversation_messages,  # Structured messages for XAI cache
                        tier="large",
                    )
                    
                    # DEBUG: Log after calling reply()
                    logger.info(f"🔍 [DEBUG_FAST_PATH] reply() returned:")
                    logger.info(f"  - type: {type(direct_response)}")
                    logger.info(f"  - length: {len(direct_response) if direct_response else 0} chars")
                    logger.info(f"  - is empty: {not direct_response}")
                    if direct_response:
                        logger.info(f"  - preview: {direct_response[:200]}...")
                    else:
                        logger.warning("⚠️ [DEBUG_FAST_PATH] reply() returned empty response!")
                    
                    # Formatting is now handled in query.py reply_llm (llm_oss) based on actual internet search usage
                    logger.info("⚡ [ORCHESTRATOR] Formatting handled in query.py - using response as-is")
                    final_response = direct_response
                    
                    processing_time = time.time() - start_time
                    
                    # Return fast response - UI parses SOURCES from response text
                    fast_response_data = {
                        "response": final_response,  # Use formatted response when internet enabled, raw otherwise
                        "strategies_used": ["model_only"],
                        "processing_time": processing_time,
                        "metadata": {
                            "total_sources": 0,
                            "agentic_rag": False,
                            "model_only_mode": True,
                            "fast_path_used": True,
                            "multi_hop_executed": False,
                            "persona_used": bool(persona_data),
                            "persona_profession": persona_data.get('persona', {}).get('profession', 'None') if persona_data else 'None',
                            "error_messages": []
                        }
                    }
                    
                    logger.info(f"⚡ Model-only fast path complete in {processing_time:.2f}s")
                    if persona_data:
                        logger.info(f"🎭 Applied persona-aware prompts for {persona_data.get('persona', {}).get('profession', 'Unknown')}")
                    
                    return fast_response_data
                    
                except Exception as e:
                    logger.error(f"❌ Model-only fast path failed: {e}")
                    # Fall back to normal processing
                    logger.info("🔄 Falling back to normal LangGraph processing")
            
            # Initialize state
            initial_state = QueryState(
                query=query,
                user_id=user_id,
                user_email=user_email,
                entity_id=entity_id,
                entity_name=entity_name,
                entity_type=entity_type,
                use_personal_data=use_personal_data,
                use_enterprise_data=use_enterprise_data,
                org_id=org_id,
                dept_id=dept_id,
                roles=roles or ["user"],
                use_saas_data=True,
                enterprise_user_info=enterprise_user_info,
                conversation_history=processed_conversation_history,
                multimodal_attachments=attachments,
                persona_data=persona_data,
                enable_internet_search=enable_internet_search,
                legal_collection_ids=legal_collection_ids or legal_collections_from_additional,
                personal_contexts=[],
                enterprise_contexts=[],
                entity_contexts=[],
                kg_contexts=[],  # Initialize knowledge graph contexts
                saas_contexts=[],  # NEW: Initialize SaaS contexts (from Milvus saas collection)
                strategies_executed=[],
                error_messages=[],
                metadata={
                    'additional_sources': additional_sources,
                    'deep_research': deep_research,
                    'query_type': query_type,
                    'model_only_mode': model_only_mode,
                    'selected_folder_ids': selected_folder_ids,  # Project management will use this
                    'folder_search_enabled': folder_search_enabled
                }
            )
            
            # Run the graph
            result = await self.graph.ainvoke(initial_state)
            
            processing_time = time.time() - start_time
            
            # Get final response with SOURCES section intact (UI parses it directly)
            final_response = result.get('final_response', 'No response generated')
            
            # Formatting is now handled in query.py reply_llm (llm_oss) based on actual internet search usage
            # No need to format here in orchestrator
            logger.info("⚡ [ORCHESTRATOR] Formatting handled in query.py - using response as-is")
            formatted_response = final_response
            
            # Prepare final response - UI parses SOURCES section directly from response text
            response_data = {
                "response": formatted_response,  # Use formatted response instead of raw
                "strategies_used": result.get('strategies_executed', []),
                "processing_time": processing_time,
                "metadata": {
                    "agentic_rag": True,
                    "multi_hop_executed": bool(result.get('multi_hop_result')),
                    "kg_retrieval_executed": bool(result.get('kg_contexts', [])),
                    "kg_contexts_count": len(result.get('kg_contexts', [])),
                    "query_intent": result.get('query_intent').__dict__ if result.get('query_intent') else None,
                    "error_messages": result.get('error_messages', []),
                    **result.get('metadata', {})
                }
            }
            
            logger.info(f"✅ Agentic RAG processing complete in {processing_time:.2f}s")
            logger.info(f"📊 Strategies executed: {result.get('strategies_executed', [])}")
            if result.get('kg_contexts'):
                logger.info(f"🧠 Knowledge graph contexts: {len(result.get('kg_contexts', []))}")
            
            return response_data
            
        except Exception as e:
            processing_time = time.time() - start_time
            logger.error(f"❌ Agentic RAG processing failed after {processing_time:.2f}s: {e}")
            
            return {
                "response": f"An error occurred during query processing: {str(e)}",
                "strategies_used": [],
                "processing_time": processing_time,
                "metadata": {
                    "error": str(e),
                    "fallback_used": True,
                    "agentic_rag": False,
                    "total_sources": 0
                }
            }
    
