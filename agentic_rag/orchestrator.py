class RetrievalStrategy(Enum):
    """Available retrieval strategies for the orchestrator"""
    PERSONAL_ONLY = "personal_only"
    ENTERPRISE = "enterprise"   # Enterprise vault + remote Citra instances
    COMBINED = "combined"  # Multiple strategies needed

@dataclass
class SubQuery:
    """Individual sub-query generated by SimplifiedStrategyPlanner"""
    query_text: str
    priority: int = 1  # 1 = highest priority
    reasoning: str = ""

@dataclass 
class QueryIntent:
    """Query intent analysis result from SimplifiedStrategyPlanner"""
    needs_decomposition: bool = False
    sub_queries: List[SubQuery] = field(default_factory=list)
    original_complexity: str = "simple"  # simple, moderate, complex
    requires_project_data: bool = False  # For project management queries
    # NOTE: SaaS data now fetched via Milvus `saas` collection semantic search
    # No need for live_data routing - SaaSDataTool handles it automatically
    
    # Query enhancement tracking
    original_query: str = ""  # Original user query
    enhanced_query: str = ""  # Query with entity context injected
    query_was_enhanced: bool = False  # Whether enhancement was applied
    
    # Legacy fields for backward compatibility
    requires_personal_context: bool = False
    reasoning: str = ""
    decomposed_queries: List[str] = field(default_factory=list)
    confidence_score: float = 0.8
    
    # Enhanced fields for retrieval
    simple_retrieval_parts: List[str] = field(default_factory=list)

