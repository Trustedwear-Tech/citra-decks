class QueryState(TypedDict):
    """State for the query processing graph"""
    # Input parameters
    query: str
    original_query: Optional[str]  # Original query before enrichment (for display)
    user_id: str
    user_email: Optional[str]  # User email for credit tracking
    vault_id: Optional[str]  # Vault ID for project management queries
    use_personal_data: bool
    conversation_history: List[Dict[str, Any]]
    multimodal_attachments: Optional[List[Dict[str, Any]]]
    persona_data: Optional[Dict[str, Any]]  # User persona data from query API
    enable_internet_search: bool  # Internet search toggle from UI
    force_internet: Optional[bool]  # Bypass adaptive gating; require internet_search this turn
    legal_collection_ids: Optional[List[str]]  # LLM collection IDs from legal filters

    # Enterprise identity (populated from JWT claims, zero extra DB calls)
    use_enterprise_data: bool           # User toggled "Enterprise Data Store" in UI
    org_id: Optional[str]               # Org this user belongs to
    dept_id: Optional[str]              # Department (finer scope)
    roles: List[str]                    # e.g. ['user'] or ['dept_admin', 'user']

    # Analysis results
    query_intent: Optional[QueryIntent]
    selected_strategies: List[RetrievalStrategy]
    decomposed_queries: List[str]  # Legacy field for backward compatibility
    sub_queries: Optional[List[SubQuery]]  # Enhanced sub-query decomposition
    
    # Data routing — vault file metadata is read from MongoDB
    # (`structured_file_metadata` + `unstructured_file_metadata`). The legacy
    # Milvus `saas` collection has been retired; the field name is kept for
    # backward compatibility with downstream consumers.
    requires_data: Optional[bool]  # Whether query needs any data at all
    use_saas_data: Optional[bool]  # Whether to include vault file metadata in retrieval (default: True)

    # Retrieval results
    personal_contexts: List[Dict[str, Any]]
    kg_contexts: List[Dict[str, Any]]  # Knowledge graph contexts for personal folders
    saas_contexts: List[Dict[str, Any]]  # Vault file schema/summary previews from MongoDB metadata
    enterprise_contexts: List[Dict[str, Any]]  # Always empty — kept for downstream-merge compatibility

    # Final results
    merged_context: str
    merged_contexts: List[Dict[str, Any]]  # Raw context chunks for chunk-based caching
    final_response: str
    metadata: Dict[str, Any]
    
    # Processing metadata
    processing_time: float
    strategies_executed: List[str]
    error_messages: List[str]

class QueryOrchestrator:
    """Main orchestrator using LangGraph for agentic RAG"""
    
    def __init__(self):
        self.simplified_planner = SimplifiedStrategyPlanner()  # Intelligent sub-query generator
        self.context_merger = ContextMerger()
        
        # Use unified source provider
        self.source_provider = get_source_provider()
        
        # Initialize retrieval tools (no LLM decisions - just data retrieval)
        # Now includes SaaSDataTool for Milvus saas collection search
        self.tools = RETRIEVAL_TOOLS
        
        # Knowledge Graph Agent disabled (env flag removed — re-add if KG pipeline is restored)
        self.kg_agent = None
        
        # Store reference to planner for legal filter extraction
        self.planner = self.simplified_planner
        
        # Structured data for chat is now handled by SaaSDataTool via source_provider.
        # Other UIs (presentation, printable, composer) call retrieve_for_query directly.
        
        self.graph = self._build_graph()
        logger.info("🚀 QueryOrchestrator initialized with SimplifiedStrategyPlanner, KG Agent, and unified source provider")
    
    def _build_graph(self) -> StateGraph:
        """Build the LangGraph workflow"""
        workflow = StateGraph(QueryState)
        
        # Add nodes
        workflow.add_node("analyze_query", self.analyze_query)
        workflow.add_node("plan_strategies", self.plan_strategies)
        workflow.add_node("execute_retrieval", self.execute_retrieval)
        workflow.add_node("execute_retrieval_with_legal_filter_fallback", self.execute_retrieval_with_legal_filter_fallback)
        workflow.add_node("merge_contexts", self.merge_contexts)
        workflow.add_node("generate_response", self.generate_response)
        
        # Set entry point
        workflow.set_entry_point("analyze_query")
        
        # Define workflow edges
        workflow.add_edge("analyze_query", "plan_strategies")
        
        # Conditional routing based on strategies
        workflow.add_conditional_edges(
            "plan_strategies",
            self.route_execution,
            {
                "retrieval": "execute_retrieval_with_legal_filter_fallback",
                "merge": "merge_contexts"
            }
        )
        
        # Regular retrieval path
        workflow.add_edge("execute_retrieval", "merge_contexts")
        workflow.add_edge("execute_retrieval_with_legal_filter_fallback", "merge_contexts")
        workflow.add_edge("merge_contexts", "generate_response")
        workflow.add_edge("generate_response", END)
        
        return workflow.compile()
    
    async def analyze_query(self, state: QueryState) -> QueryState:
        """Analyze query intent using SimplifiedStrategyPlanner for intelligent sub-query generation"""
        try:
            logger.info(f"🧠 Analyzing query: '{state['query'][:100]}...'")
            
            # Store original query for reference
            original_query = state['query']
            state['original_query'] = original_query
            
            # Prepare user persona data
            persona_data = state.get('persona_data', {})
            
            # Extract profession - handle both nested and flat structures
            if isinstance(persona_data.get('persona'), dict):
                profession = persona_data['persona'].get('profession', 'General User')
            else:
                profession = persona_data.get('profession', 'General User')
            
            logger.info(f"👤 User profession: {profession}")
            
            # Store profession in state for citation control
            state['profession'] = profession
            
            # Available sources - personal only
            available_sources = {
                'personal': state.get('use_personal_data', True),
                'multi_hop': True  # Multi-hop is always available if needed
            }
            
            # ═══════════════════════════════════════════════════════════════════
            # SaaS DATA: Conditionally enabled — conditions:
            #   1. INCLUDE_SUPPLEMENTARY_SOURCES=true in .env
            #   2. use_personal_data is True in state
            #   3. folder_ids is provided (non-empty) — from metadata.selected_folder_ids
            # Structured files surface schema-only previews + sandbox execution
            # (see services/structured_file_listing.py + services/structured_sandbox.py).
            # ═══════════════════════════════════════════════════════════════════
            import os as _os
            _env_saas = _os.getenv("INCLUDE_SUPPLEMENTARY_SOURCES", "false").lower() == "true"
            _use_personal = state.get('use_personal_data', False)
            _folder_ids = state.get('metadata', {}).get('selected_folder_ids', []) or []
            state['use_saas_data'] = bool(
                _env_saas and _use_personal and _folder_ids
            )
            logger.info(
                f"📊 SaaS data search: {'enabled' if state['use_saas_data'] else 'disabled'} "
                f"(env={_env_saas}, personal={_use_personal}, "
                f"folders={bool(_folder_ids)})"
            )
            
            # ── Agentic mode: NO sub-query planner LLM ───────────────────────
            # The chat LLM is itself agentic — at answer time it decides what to
            # retrieve via personal_data_tool / dept_* MCP tools. A separate
            # planner LLM here only added a serial LLM round-trip to first-token
            # latency without changing what the agent ultimately fetches. Pass the
            # query through unchanged as a single sub-query — the exact shape the
            # downstream retrieval/merge path already handles (identical to the
            # former analysis-failure fallback, which is known-good).
            state['query_intent'] = QueryIntent(
                needs_decomposition=False,
                sub_queries=[SubQuery(query_text=original_query, priority=1)],
                original_complexity='simple',
                original_query=original_query,
                enhanced_query=original_query,
            )
            state['sub_queries'] = state['query_intent'].sub_queries
            state['decomposed_queries'] = [original_query]
            state['requires_data'] = True
            logger.info(
                "🧠 [ANALYZE] sub-query planner skipped (agentic) — query passed "
                "through as a single sub-query; chat LLM drives retrieval"
            )
            
        except Exception as e:
            logger.error(f"❌ Query analysis failed: {e}", exc_info=True)
            # Fallback: create simple single sub-query
            state['query_intent'] = QueryIntent(
                needs_decomposition=False,
                sub_queries=[SubQuery(
                    query_text=state['query'],
                    priority=1,
                    reasoning='Fallback due to analysis error'
                )],
                original_complexity='simple',
                original_query=state['query'],
                enhanced_query=state['query']
            )
            state['sub_queries'] = state['query_intent'].sub_queries
            state['decomposed_queries'] = [state['query']]
            state['error_messages'] = state.get('error_messages', []) + [f"Query analysis failed: {str(e)}"]
        
        return state
    
    async def plan_strategies(self, state: QueryState) -> QueryState:
        """
        Plan retrieval strategies based on enabled sources and LLM analysis
        
        NEW ARCHITECTURE:
        - SimplifiedStrategyPlanner generates optimized query text
        - Orchestrator decides which tools to use based on:
          1. use_personal_data flag
        """
        try:
            logger.info("🎯 Planning retrieval strategies...")
            
            intent = state['query_intent']
            if not intent:
                logger.error("❌ No query intent available for strategy planning")
                state['selected_strategies'] = [RetrievalStrategy.PERSONAL_ONLY]
                return state
            
            strategies = []
            
            logger.info(f"📊 Source availability:")
            logger.info(f"   - Personal: {state.get('use_personal_data', True)}")
            logger.info(f"   - Enterprise: {state.get('use_enterprise_data', False)}")
            
            # PERSONAL STRATEGY
            if state.get('use_personal_data', True):
                strategies.append(RetrievalStrategy.PERSONAL_ONLY)
                logger.info("✅ Added PERSONAL_ONLY strategy")
            else:
                logger.info("⏭️ Skipping PERSONAL_ONLY strategy (use_personal_data=False)")
            
            # ENTERPRISE STRATEGY — added independently; combined with personal if both on
            if state.get('use_enterprise_data', False):
                strategies.append(RetrievalStrategy.ENTERPRISE)
                logger.info("✅ Added ENTERPRISE strategy")
            
            # Fallback if no strategies — only add personal if use_personal_data was not explicitly disabled
            if not strategies:
                if state.get('use_personal_data', True):
                    strategies.append(RetrievalStrategy.PERSONAL_ONLY)
                    logger.info("ℹ️ No strategies determined, using PERSONAL_ONLY fallback")
                else:
                    logger.info("ℹ️ No strategies and vault disabled — model-only mode, skipping retrieval")
            
            state['selected_strategies'] = strategies
            logger.info(f"🎯 Final strategy plan: {[s.value for s in strategies]}")
            
        except Exception as e:
            logger.error(f"❌ Strategy planning failed: {e}")
            state['error_messages'] = state.get('error_messages', []) + [f"Strategy planning failed: {str(e)}"]
            # Fallback to personal only
            state['selected_strategies'] = [RetrievalStrategy.PERSONAL_ONLY]
        
        return state
    
    def route_execution(self, state: QueryState) -> str:
        """Route to appropriate execution path"""
        strategies = state.get('selected_strategies', [])
        
        # If any retrieval strategies are needed
        if strategies:
            return "retrieval"
        
        # Fallback to merge (with empty contexts)
        return "merge"
    
    async def execute_retrieval(self, state: QueryState) -> QueryState:
        """Execute retrieval strategies using unified source provider."""
        try:
            logger.info("🔍 Executing retrieval strategies...")
            
            strategies = state.get('selected_strategies', [])
            query_intent = state.get('query_intent')

            # Build SourceConfig — after the agentic-tool refactor, the only
            # pre-fetched source is SaaSDataTool (Mongo file-listing metadata).
            # Personal vault chunks and enterprise data are fetched on-demand
            # by the chat LLM via `personal_data_tool` and `dept_*` MCP tools.
            source_config = self.source_provider.build_source_config_from_strategies(strategies, state)

            async def fetch_all_contexts():
                """Pre-fetch file-listing metadata via SaaSDataTool (Mongo).

                Sub-queries from the planner are intentionally NOT used here:
                file listings are scoped by user_id + folder_ids, not by query
                semantics, so one call suffices. The planner's sub_queries
                surface again inside `personal_data_tool` when the chat LLM
                actually fetches vault chunks on demand.
                """
                query_to_use = state['query']
                if query_intent and query_intent.sub_queries and len(query_intent.sub_queries) == 1:
                    # Single sub-query is a refined version of state['query'] —
                    # use it for slightly better file-relevance scoring.
                    query_to_use = query_intent.sub_queries[0].query_text
                contexts_by_source = await self.source_provider.retrieve_from_sources(
                    query=query_to_use,
                    user_id=state['user_id'],
                    source_config=source_config,
                    context_label="file_metadata_prefetch",
                    user_email=state.get('user_email'),
                )
                total_contexts = sum(len(c) for c in contexts_by_source.values())
                logger.info(f"✅ File-metadata pre-fetch: {total_contexts} chunk(s)")
                return contexts_by_source

            logger.info("🚀 Starting file-metadata pre-fetch (personal vault chunks fetched agentically by chat LLM)...")
            contexts_by_source = await fetch_all_contexts()
            logger.info("✅ Pre-fetch complete")
            
            # Process results
            total_contexts = sum(len(contexts) for contexts in contexts_by_source.values())
            
            # Store retrieved contexts in state (maintaining backward compatibility).
            # personal_contexts is always empty after the agentic-tool refactor —
            # the chat LLM fetches Milvus chunks via personal_data_tool on demand.
            state['personal_contexts'] = []
            state['saas_contexts'] = contexts_by_source.get('saas', [])  # File-listing metadata from Mongo
            state['contexts_by_source'] = contexts_by_source

            # ═══════════════════════════════════════════════════════════════════
            # ENTERPRISE: orchestrator pre-fetch is DEPRECATED. All enterprise
            # retrieval now happens via the LLM-callable `dept_*` MCP tools
            # surfaced in streaming_response.py. Keep the state field empty for
            # backward compatibility with downstream merging logic.
            # ═══════════════════════════════════════════════════════════════════
            state['enterprise_contexts'] = []
            
            # Log SaaS retrieval results
            saas_count = len(state['saas_contexts'])
            if saas_count > 0:
                logger.info(f"✅ [SAAS] Retrieved {saas_count} contexts from Milvus saas collection")
                state['strategies_executed'] = state.get('strategies_executed', []) + ['saas_search']
            else:
                logger.info("⏭️ [SAAS] No SaaS data found (user may not have connected sources)")
            
            # ═══════════════════════════════════════════════════════════════════
            # SEQUENTIAL: Knowledge Graph (less common)
            # ═══════════════════════════════════════════════════════════════════
            
            # 🧠 KNOWLEDGE GRAPH RETRIEVAL: Disabled (env flag removed)
            state['kg_contexts'] = []
            
            # ═══════════════════════════════════════════════════════════════════
            # NOTE: SaaS DATA is now retrieved automatically via SaaSDataTool
            # - Data is pre-embedded into Milvus `saas` collection by file upload
            # - SaaSDataTool performs semantic search in parallel with personal data
            # - No need for separate live_data fetching or AI routing
            # ═══════════════════════════════════════════════════════════════════
            
            # Track executed strategies (excluding removed MULTI_HOP)
            executed_strategies = [s.value for s in strategies]
            state['strategies_executed'] = state.get('strategies_executed', []) + executed_strategies
            
            logger.info(f"✅ Retrieval execution complete - {total_contexts} total contexts from {len(contexts_by_source)} sources")
            
        except Exception as e:
            logger.error(f"❌ Retrieval execution failed: {e}")
            state['error_messages'] = state.get('error_messages', []) + [f"Retrieval execution failed: {str(e)}"]
        
        return state

